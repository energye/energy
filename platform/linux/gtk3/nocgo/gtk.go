func Init(args *[]string) {
	if args == nil {
		gtk3.SysCall("gtk_init", 0, 0)
		return
	}

	argc := int32(len(*args))
	argv, items := makeCStringArray(*args)
	defer freeCStringArray(argv, items)

	gtk3.SysCall("gtk_init", uintptr(unsafe.Pointer(&argc)), uintptr(unsafe.Pointer(&argv)))

	unhandled := make([]string, int(argc))
	for i := 0; i < int(argc); i++ {
		cstr := *(*uintptr)(unsafe.Pointer(argv + uintptr(i)*ptrSize))
		unhandled[i] = GoStr(cstr)
	}
	*args = unhandled
}

